import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

// Writes supabase/functions/llm/prompts/<name>.ts from content/json/prompts.json, verbatim (BUILD_PLAN 8.2).
// Run after `npm run content` whenever the Testing Architecture changes; a unit test fails if they drift.
export const PROMPT_DIR = join('supabase', 'functions', 'llm', 'prompts');

export function promptFile(text: string): string {
  return `// Generated by scripts/sync-prompts.ts from content/json/prompts.json. Do not edit by hand.\nexport default ${JSON.stringify(text)};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const prompts: Record<string, string> = JSON.parse(readFileSync('content/json/prompts.json', 'utf8'));
  mkdirSync(PROMPT_DIR, { recursive: true });
  for (const [name, text] of Object.entries(prompts)) writeFileSync(join(PROMPT_DIR, `${name}.ts`), promptFile(text));
  const names = Object.keys(prompts);
  writeFileSync(
    join(PROMPT_DIR, 'index.ts'),
    `// Generated by scripts/sync-prompts.ts. Do not edit by hand.\n${names.map((n) => `import ${n} from './${n}.ts';`).join('\n')}\n\nexport const PROMPTS = { ${names.join(', ')} };\n`,
  );
  console.log(`Wrote ${names.length} prompts to ${PROMPT_DIR}`);
}
