export interface Issue {
  where: string;
  message: string;
}

export class Report {
  errors: Issue[] = [];
  warnings: Issue[] = [];
  dashes: { where: string; from: string; to: string }[] = [];
  lowConfidence: Issue[] = [];
  tapWithoutOptions: string[] = [];
  notes: string[] = [];
  counts: { unit: string; drills: number; tap: number; cards: number; comprehension: number; lessonSections: number }[] = [];

  error(where: string, message: string) {
    this.errors.push({ where, message });
  }
  warn(where: string, message: string) {
    this.warnings.push({ where, message });
  }
  dash(where: string, from: string, to: string) {
    this.dashes.push({ where, from, to });
  }
  low(where: string, message: string) {
    this.lowConfidence.push({ where, message });
  }

  toMarkdown(): string {
    const out: string[] = ['# Parse report', '', 'Generated by `npm run content`. Do not edit by hand.', ''];
    out.push(`Errors: ${this.errors.length}. Warnings: ${this.warnings.length}. Low-confidence mappings: ${this.lowConfidence.length}. Dash replacements: ${this.dashes.length}.`, '');

    out.push('## Errors (these fail validation)', '');
    out.push(...(this.errors.length ? this.errors.map((e) => `- \`${e.where}\`: ${e.message}`) : ['None.']), '');

    out.push('## Warnings', '');
    out.push(...(this.warnings.length ? this.warnings.map((e) => `- \`${e.where}\`: ${e.message}`) : ['None.']), '');

    out.push('## Counts per unit', '', '| Unit | Drills | of which TAP | Cards | Comprehension | Lesson sections |', '| --- | --- | --- | --- | --- | --- |');
    for (const c of this.counts) out.push(`| ${c.unit} | ${c.drills} | ${c.tap} | ${c.cards} | ${c.comprehension} | ${c.lessonSections} |`);
    out.push('');

    out.push('## Reclassified to keyed: marked TAP in the source with no options', '');
    out.push('Owner decision 2026-10-19: these are keyed drills graded against their written key. No options are invented. Each keeps `tapTagged: true` for traceability.', '');
    out.push(...(this.tapWithoutOptions.length ? this.tapWithoutOptions.map((d) => `- \`${d}\``) : ['None.']), '');

    out.push('## Low-confidence mappings', '');
    out.push(...(this.lowConfidence.length ? this.lowConfidence.map((e) => `- \`${e.where}\`: ${e.message}`) : ['None.']), '');

    out.push('## Dash replacements', '');
    out.push(...(this.dashes.length ? this.dashes.map((d) => `- \`${d.where}\`: "${d.to.trim()}"`) : ['None.']), '');

    out.push('## Notes', '');
    out.push(...(this.notes.length ? this.notes.map((n) => `- ${n}`) : ['None.']), '');
    return out.join('\n');
  }
}
